"""Read item silhouettes and save layout metadata; never edit source PNGs."""
from pathlib import Path
from PIL import Image
import numpy as np,json
root=Path(__file__).resolve().parent.parent;im=np.array(Image.open(root/'public/assets/relic-items.png').convert('RGBA'));alpha=im[:,:,3];h,w=alpha.shape;result={}
for row,name in enumerate(['heal','ice','cursed','royal']):
 frames=[]
 for col in range(8):
  x0,x1=round(col*w/8),round((col+1)*w/8);y0,y1=round(row*h/4),round((row+1)*h/4);ys,xs=np.where(alpha[y0:y1,x0:x1]>8)
  if len(xs)<500:raise ValueError(f'Empty item {row}/{col}')
  left,right,top,bottom=x0+int(xs.min()),x0+int(xs.max())+1,y0+int(ys.min()),y0+int(ys.max())+1
  if left<2 or top<2 or right>w-2 or bottom>h-2:raise ValueError(f'Item touches source edge: {row}/{col}')
  frames.append([left,top,right-left,bottom-top])
 result[name]={'scale':72/max(max(f[2],f[3]) for f in frames),'frames':frames}
(root/'public/item-layouts.js').write_text('// Generated by scripts/analyze-items.py; original PNG is unchanged.\nexport const ITEM_LAYOUTS='+json.dumps(result,separators=(',',':'))+';\n')
print('32 complete item poses; source edges clear.')
